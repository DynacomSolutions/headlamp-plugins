// Writes src/nodes/bundledIcons.generated.ts: the small subset of Simple Icons and Material
// Design Icons the dashboard uses, so Iconify never fetches an icon from api.iconify.design.
// Run: node scripts/gen-bundled-icons.mjs (needs the two @iconify-json dev dependencies).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const load = name => JSON.parse(readFileSync(require.resolve(`@iconify-json/${name}/icons.json`), 'utf8'));

const WANTED = {
  'simple-icons': `nodedotjs npm bun deno python go rust openjdk anthropic claude openai kimi git github
    gnubash zsh googlechrome firefox postgresql redis nginx caddy traefikproxy grafana prometheus
    victoriametrics argo containerd kubernetes sqlite docker podman vite esbuild typescript
    playwright ffmpeg gnometerminal`,
  mdi: `kubernetes console robot folder folder-outline cog cog-outline cube-outline server ssh dns
    linux sheep code-braces hammer-wrench desk-lamp view-grid-outline chat-processing-outline
    arrow-up selection-ellipse magnify-plus fullscreen-exit google-chrome language-java`,
};

let out = `// Generated by scripts/gen-bundled-icons.mjs. Do not edit.
// Subset of @iconify-json/simple-icons (CC0) and @iconify-json/mdi (Apache-2.0).
export const BUNDLED_ICONS: Record<string, Record<string, string>> = {\n`;
for (const [prefix, names] of Object.entries(WANTED)) {
  const set = load(prefix);
  out += `  '${prefix}': {\n`;
  for (const n of names.split(/\s+/).filter(Boolean).sort()) {
    const icon = set.icons[n];
    if (!icon) throw new Error(`${prefix}:${n} not found`);
    out += `    '${n}': ${JSON.stringify(icon.body)},\n`;
  }
  out += '  },\n';
}
out += '};\n';
writeFileSync(new URL('../src/nodes/bundledIcons.generated.ts', import.meta.url), out);
