// Writes src/widgets/ais/providerIcons.generated.ts: the official logos of the AI providers that the
// AIS widgets name, as plain path data, so the plugin never fetches a logo from a third-party host.
// Sources (checked in this order): simple-icons (CC0), then @lobehub/icons-static-svg (MIT).
// The logos stay the trademarks of their owners.
// Run: node scripts/gen-provider-icons.mjs <simple-icons dir> <lobe-icons icons dir>
//   <simple-icons dir> holds the "icons" folder of the simple-icons package.
//   <lobe-icons icons dir> holds the "icons" folder of @lobehub/icons-static-svg.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [simple, lobe] = process.argv.slice(2);
if (!simple || !lobe) throw new Error('Usage: gen-provider-icons.mjs <simple-icons> <lobe-icons>');

/** One entry for each logo: the id, the source package, the file, and the brand it shows. */
const LOGOS = [
  { id: 'claude', from: lobe, file: 'claude-color.svg', brand: 'Claude' },
  { id: 'anthropic', from: simple, file: 'anthropic.svg', brand: 'Anthropic' },
  { id: 'openai', from: lobe, file: 'openai.svg', brand: 'OpenAI' },
  { id: 'kimi', from: lobe, file: 'kimi-color.svg', brand: 'Kimi' },
  { id: 'opencode', from: simple, file: 'opencode.svg', brand: 'OpenCode' },
  { id: 'xai', from: lobe, file: 'xai.svg', brand: 'xAI' },
  { id: 'zai', from: lobe, file: 'zai.svg', brand: 'Z.ai' },
  { id: 'pi', from: simple, file: 'pi.svg', brand: 'Pi' },
  { id: 'alibaba', from: lobe, file: 'alibabacloud-color.svg', brand: 'Alibaba Cloud' },
  { id: 'google', from: lobe, file: 'google-color.svg', brand: 'Google' },
];

const attr = (tag, name) => new RegExp(`\\s${name}="([^"]*)"`).exec(tag)?.[1];

const out = LOGOS.map(({ id, from, file, brand }) => {
  const svg = readFileSync(join(from, file), 'utf8');
  const viewBox = attr(svg.match(/<svg[^>]*>/)[0], 'viewBox');
  if (viewBox !== '0 0 24 24') throw new Error(`${file}: unexpected viewBox ${viewBox}`);
  if (/<(?!\/?(svg|title|path)\b)[a-zA-Z]/.test(svg))
    throw new Error(`${file}: only <path> is supported`);
  const rootFill = attr(svg.match(/<svg[^>]*>/)[0], 'fill');
  const rootRule = attr(svg.match(/<svg[^>]*>/)[0], 'fill-rule');
  const paths = [...svg.matchAll(/<path\b[^>]*>/g)].map(m => {
    const tag = m[0];
    const fill = attr(tag, 'fill') ?? rootFill;
    const rule = attr(tag, 'fill-rule') ?? rootRule;
    const clip = attr(tag, 'clip-rule');
    return `{ d: ${JSON.stringify(attr(tag, 'd'))}${
      fill && fill !== 'currentColor' ? `, fill: ${JSON.stringify(fill)}` : ''
    }${rule ? `, fillRule: ${JSON.stringify(rule)}` : ''}${
      clip ? `, clipRule: ${JSON.stringify(clip)}` : ''
    } }`;
  });
  if (paths.length === 0) throw new Error(`${file}: no path`);
  return `  ${id}: {\n    brand: ${JSON.stringify(brand)},\n    paths: [\n      ${paths.join(
    ',\n      '
  )},\n    ],\n  },`;
});

writeFileSync(
  new URL('../src/widgets/ais/providerIcons.generated.ts', import.meta.url),
  `// Generated by scripts/gen-provider-icons.mjs. Do not edit.
// Logos from simple-icons (CC0) and @lobehub/icons-static-svg (MIT). They stay the trademarks of their owners.
// A path without "fill" uses the text colour of its place, so it reads on the dark and the light theme.
export interface ProviderLogo {
  brand: string;
  paths: Array<{ d: string; fill?: string; fillRule?: 'evenodd' | 'nonzero'; clipRule?: 'evenodd' | 'nonzero' }>;
}

export const PROVIDER_LOGOS: Record<string, ProviderLogo> = {
${out.join('\n')}
};
`
);
console.log(`Wrote ${LOGOS.length} logos`);
